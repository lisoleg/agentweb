// =============== Main Panel ===============

const SentimentITAPanel: React.FC = () => {
  const [activeTab, setActiveTab] = useState(0);

  return (
    <Box>
      <Box sx={{ borderBottom: 1, borderColor: 'divider', mb: 2 }}>
        <Tabs value={activeTab} onChange={(_, v) => setActiveTab(v)}>
          <Tab label="📊 舆情监测" />
          <Tab label="🔗 ITA触发链路" />
          <Tab label="💰 补偿方案" />
        </Tabs>
      </Box>
      {activeTab === 0 && <MonitoringTab />}
      {activeTab === 1 && <ITAChainTab />}
      {activeTab === 2 && <CompensateTab />}
    </Box>
  );
};

export default SentimentITAPanel;
